/** p gives the privacy and guardian wording in the app's language. */
export const p = () => (language() === "zh-CN" ? zh : en);

const pad = (n: number) => String(n).padStart(2, "0");

/** dateOf writes a time in milliseconds since the epoch as YYYY-MM-DD on this device. */
export function dateOf(at: bigint | number): string {
  const date = new Date(Number(at));
  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}`;
}
