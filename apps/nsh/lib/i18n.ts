const authMessages = {
  INVALID_EMAIL_OR_PASSWORD: "badLogin",
  INVALID_USERNAME_OR_PASSWORD: "badLogin",
  USER_ALREADY_EXISTS: "emailTaken",
  USER_ALREADY_EXISTS_USE_ANOTHER_EMAIL: "emailTaken",
  PASSWORD_TOO_SHORT: "weakPassword",
  USERNAME_IS_ALREADY_TAKEN: "usernameTaken",
  INVALID_USERNAME: "usernameInvalid",
  USERNAME_TOO_SHORT: "usernameInvalid",
  USERNAME_TOO_LONG: "usernameInvalid",
  INVALID_PASSWORD: "badPassword",
} as const;

/** errorText words a failed call for the person who made it. */
export function errorText(error: unknown): string {
  if (error instanceof AuthError) {
    const key = authMessages[error.code as keyof typeof authMessages];
    return key ? m()[key] : m().error;
  }
  if (failureOf(error) === "offline") return m().offlineBody;
  if (failureOf(error) === "plan") return m().noPlanBody;
  const raw = ConnectError.from(error).rawMessage;
  if (raw === "too many texts in a minute; wait a moment") return m().judgingRate;
  if (raw === "today's texts are used up; come back tomorrow") return m().judgingDaily;
  return raw === "that date is not valid" ? m().invalidDate : m().error;
}
