const O: Point = [0, 0];

const square = (c: Point, k: number): Mark => ({
  kind: "polygon",
  points: [
    [c[0] - k, c[1] - k],
    [c[0] + k, c[1] - k],
    [c[0] + k, c[1] + k],
    [c[0] - k, c[1] + k],
  ],
});

// A square of four beads, of which the listed corners are filled, counterclockwise from the lower left.
const coloring = (c: Point, filled: readonly number[]): Mark[] => {
  const k = 0.7;
  const corners: Point[] = [
    [c[0] - k, c[1] - k],
    [c[0] + k, c[1] - k],
    [c[0] + k, c[1] + k],
    [c[0] - k, c[1] + k],
  ];
  return [
    square(c, k),
    ...corners.flatMap((p, i): Mark[] => [disc(p, 0.24, undefined, filled.includes(i) ? "result" : "action"), ring(0.24, p)]),
  ];
};

// Boxes in a row, each holding the elements of a class, starting at x and sized by the number of its elements.
const classes = (x: number, y: number, boxes: readonly (readonly string[])[]): Mark[] => {
  let at = x;
  return boxes.flatMap((box): Mark[] => {
    const w = box.length * 1.4;
    const left = at;
    at += w + 0.3;
    return [
      {
        kind: "polygon",
        points: [
          [left, y],
          [left + w, y],
          [left + w, y + 1.4],
          [left, y + 1.4],
        ],
      },
      ...box.map((text, i) => note([left + (i + 0.5) * 1.4, y + 0.3], text, "n")),
    ];
  });
};

