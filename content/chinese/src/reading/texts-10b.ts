开放当天，来借书的村民有一百多人。七十岁的村民张大爷借了一本讲种果树的书，他说：“以前想查点东西，要跑到县城，现在家门口就有了。”
据县文化局介绍，今后三年，全县还将在二十个村建设同样的图书馆。县文化局局长表示，乡村图书馆不只是借书的地方，也要成为村民学习和交流的场所。
