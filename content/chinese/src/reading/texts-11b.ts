你可以给他们的身体一个家，却不能给他们的灵魂一个家，
因为他们的灵魂住在明天，那是你连做梦也到不了的地方。
你可以努力去像他们，却不要让他们来像你。
因为生命只向前走，不会停在昨天。
你是一张弓，孩子是从你这里射出去的、有生命的箭。
