// Grade 3: short stories written for the reading skills of the course. Each is read for its setting, problem and
// solution, how its main character changes, the key events a retelling keeps, and how one action moves the plot.

/** Tale is a short story and what a reader should find in it. */
export interface Tale {
  readonly who: string;
  readonly text: string;
  /** setting is the right setting, then two that the story does not support. */
  readonly setting: readonly [string, string, string];
  readonly problem: string;
  /** detail happens in the story but is not its problem. */
  readonly detail: string;
  readonly solution: string;
  /** notSolution happens in the story but does not solve the problem. */
  readonly notSolution: string;
  /** change is how the character is at the beginning, at the end, and a wrong end. */
  readonly change: readonly [string, string, string];
  /** changed is the event that changes the character. */
  readonly changed: string;
  /** events are the three key events in order. */
  readonly events: readonly [string, string, string];
  /** details are two small details a retelling leaves out. */
  readonly details: readonly [string, string];
  readonly action: string;
  readonly caused: string;
  /** notHappen is a result that does not happen in the story. */
  readonly notHappen: string;
  /** alt is what a character might have done instead, as "Pip had kept the acorns". */
  readonly alt: string;
  readonly ifRight: string;
  readonly ifOdd: string;
}

